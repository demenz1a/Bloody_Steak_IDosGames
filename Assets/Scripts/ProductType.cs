/// <summary>
/// Все возможные состояния мясного продукта на его пути от сырого мяса до готового блюда
/// (или подгоревшего). Один и тот же физический объект Product меняет свой Type
/// по ходу готовки — новый объект не создаётся.
/// </summary>
public enum ProductType
{
    RawMeat,
    Steak1,   // слегка прожаренный (гриль, стадия 1)
    Steak2,   // сильно прожаренный (гриль, стадия 2)
    Sausage,  // мясорубка
    Skewer,   // шампуры
    Burned    // сгорело — не годится для заказа
}
