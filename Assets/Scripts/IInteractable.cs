/// <summary>
/// Реализуют все объекты, с которыми игрок может взаимодействовать по кнопке Space:
/// стол с мясом, станции готовки, стойка выдачи, НПС (убийство), машина переработки, дверь кухни и т.д.
/// </summary>
public interface IInteractable
{
    /// <summary>
    /// Доступно ли взаимодействие ПРЯМО СЕЙЧАС для этого игрока.
    /// Здесь должна проверяться вся логика сразу: состояние объекта (пусто/готовится/готово),
    /// содержимое рук игрока, текущая форма игрока (Sheep/Wolf), и любые доп. условия
    /// (например, для НПС — можно ли убивать незаметно).
    /// </summary>
    bool CanInteract(PlayerInteractor player);

    /// <summary>
    /// Выполнить действие. Вызывается ТОЛЬКО когда CanInteract уже вернул true —
    /// сам метод не обязан повторно всё перепроверять.
    /// </summary>
    void Interact(PlayerInteractor player);
}