/// <summary>
/// Одна стадия готовности продукта на станции.
/// Массив стадий у CookingStation задаёт весь путь приготовления:
/// у шампуров/мясорубки — одна стадия (сырое -> готово),
/// у гриля — две (слегка прожаренный -> сильно прожаренный) — именно это
/// и делает его "особой" станцией из ТЗ, без единой строчки особого кода.
/// Стадии должны идти в инспекторе по возрастанию timeToReach.
///
/// В отличие от старой версии, здесь нет спрайта — станция просто говорит
/// продукту "стань resultType", а сам продукт (Product.cs) знает, как выглядеть.
/// </summary>
[System.Serializable]
public class CookingStage
{
    public ProductType resultType;

    public float timeToReach = 5f;

    /// <summary>Можно ли забрать продукт на этой стадии и использовать для заказа.</summary>
    public bool isServable = true;
}
